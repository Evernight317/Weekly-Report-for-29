public class Constuctor_Fu {
    private String name;
    private int age;
    public Constuctor_Fu(String name, int age) {
        this.name = name;
        this.age = age;
    }
    public Constuctor_Fu() {
    }
    public String getName() {
        return name;
    }
    public void setName(String name) {
        this.name = name;
    }
    public int getAge() {
        return age;
    }
    public void setAge(int age) {
        this.age = age;
    }
}
